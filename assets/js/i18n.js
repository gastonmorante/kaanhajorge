/**
 * Helper function to translate page content based on [data-i18n] attributes
 */
window.translatePage = function (lang) {
  const dictionary = window.I18N_DATA[lang] || window.I18N_DATA.es;

  // Translate all text elements
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dictionary[key] !== undefined) {
      el.textContent = dictionary[key];
    }
  });

  // Translate placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dictionary[key] !== undefined) {
      el.setAttribute("placeholder", dictionary[key]);
    }
  });

  // Update HTML lang attribute
  document.documentElement.setAttribute("lang", lang);

  // Update active state in language selector pills
  document.querySelectorAll(".lang-btn").forEach(btn => {
    const btnLang = btn.getAttribute("data-lang");
    if (btnLang === lang) {
      btn.classList.add("bg-matte-gold", "text-deep-jungle", "font-bold");
      btn.classList.remove("text-arena-chukum/70", "hover:text-white");
    } else {
      btn.classList.remove("bg-matte-gold", "text-deep-jungle", "font-bold");
      btn.classList.add("text-arena-chukum/70", "hover:text-white");
    }
  });

  // Notify carousel to update slide captions if available
  if (typeof window.updateCarouselCaptions === "function") {
    window.updateCarouselCaptions(lang);
  }
};
